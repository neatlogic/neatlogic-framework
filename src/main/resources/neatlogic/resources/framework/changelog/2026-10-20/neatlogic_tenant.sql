    `script_timeout` INT NOT NULL COMMENT '脚本执行超时秒数快照',
    `status` VARCHAR(30) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL COMMENT '检查项状态',
    `phase_list` MEDIUMTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci COMMENT '执行阶段结果JSON数组',
    `response_snapshot` MEDIUMTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci COMMENT '脱敏响应快照JSON',
