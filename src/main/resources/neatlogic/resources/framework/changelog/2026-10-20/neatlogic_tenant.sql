CREATE TABLE IF NOT EXISTS `selfcheck_scenario` (
    `id` BIGINT NOT NULL COMMENT '场景ID',
    `name` VARCHAR(100) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL COMMENT '场景名称',
    `description` VARCHAR(500) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '场景说明',
    `status` VARCHAR(20) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL COMMENT '场景状态',
    `version` INT NOT NULL DEFAULT 1 COMMENT '乐观锁版本',
    `fcu` CHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL COMMENT '创建人',
    `fcd` TIMESTAMP(3) NOT NULL COMMENT '创建时间',
    `lcu` CHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL COMMENT '修改人',
    `lcd` TIMESTAMP(3) NOT NULL COMMENT '修改时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_name` (`name`),
    KEY `idx_status` (`status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='功能自检场景';

CREATE TABLE IF NOT EXISTS `selfcheck_scenario_item` (
    `id` BIGINT NOT NULL COMMENT '检查项ID',
    `scenario_id` BIGINT NOT NULL COMMENT '场景ID',
    `name` VARCHAR(100) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL COMMENT '检查项名称',
    `is_active` TINYINT NOT NULL DEFAULT 1 COMMENT '是否启用',
    `sort` INT NOT NULL DEFAULT 0 COMMENT '执行顺序',
    `api_token` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL COMMENT '自检API标识',
    `request_param` MEDIUMTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci COMMENT 'API请求参数JSON',
    `verify_script` MEDIUMTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL COMMENT 'JavaScript验真脚本',
    `is_script_valid` TINYINT NOT NULL DEFAULT 0 COMMENT '脚本是否通过后端编译',
    `script_diagnostic_list` MEDIUMTEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci COMMENT '脚本诊断JSON数组',
    `api_timeout` INT NOT NULL DEFAULT 30 COMMENT 'API执行超时秒数',
    `script_timeout` INT NOT NULL DEFAULT 3 COMMENT '脚本执行超时秒数',
    PRIMARY KEY (`id`),
    KEY `idx_scenario_id_sort` (`scenario_id`, `sort`),
    KEY `idx_api_token` (`api_token`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='功能自检场景检查项';

CREATE TABLE IF NOT EXISTS `selfcheck_run` (
    `id` BIGINT NOT NULL COMMENT '执行ID',
    `scenario_id` BIGINT DEFAULT NULL COMMENT '场景ID，单项调试为空',
    `scenario_name` VARCHAR(100) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL COMMENT '场景名称快照',
    `scenario_version` INT DEFAULT NULL COMMENT '场景版本快照',
    `trigger_type` VARCHAR(20) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL COMMENT '触发方式',
    `status` VARCHAR(30) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL COMMENT '运行状态',
    `running_key` VARCHAR(100) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '运行中唯一标识',
    `executor_uuid` CHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci DEFAULT NULL COMMENT '执行人UUID',
    `server_id` INT NOT NULL COMMENT '执行节点ID',
    `item_count` INT NOT NULL DEFAULT 0 COMMENT '检查项总数',
    `success_count` INT NOT NULL DEFAULT 0 COMMENT '成功检查项数量',
    `failed_count` INT NOT NULL DEFAULT 0 COMMENT '失败检查项数量',
    `start_time` TIMESTAMP(3) NULL COMMENT '开始时间',
    `end_time` TIMESTAMP(3) NULL COMMENT '结束时间',
    `duration_ms` BIGINT DEFAULT NULL COMMENT '执行耗时毫秒',
    `error_message` TEXT CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci COMMENT '运行错误信息',
    `fcu` CHAR(32) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL COMMENT '创建人',
    `fcd` TIMESTAMP(3) NOT NULL COMMENT '创建时间',
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_running_key` (`running_key`),
    KEY `idx_scenario_id_fcd` (`scenario_id`, `fcd`),
    KEY `idx_status_server_id` (`status`, `server_id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_general_ci COMMENT='功能自检运行记录';

CREATE TABLE IF NOT EXISTS `selfcheck_run_item` (
    `id` BIGINT NOT NULL COMMENT '执行项ID',
    `run_id` BIGINT NOT NULL COMMENT '运行记录ID',
    `scenario_item_id` BIGINT DEFAULT NULL COMMENT '来源检查项ID，单项调试为空',
