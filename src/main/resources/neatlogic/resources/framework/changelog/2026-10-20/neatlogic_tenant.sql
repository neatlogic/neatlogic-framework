    `sort` INT NOT NULL DEFAULT 0 COMMENT '执行顺序快照',
    `api_token` VARCHAR(255) CHARACTER SET utf8mb4 COLLATE utf8mb4_general_ci NOT NULL COMMENT 'API标识快照',
